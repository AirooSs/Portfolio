import { vi } from 'vitest';
import { TestBed } from '@angular/core/testing';
import { App } from './app';

describe('App', () => {
  beforeEach(async () => {
    await TestBed.configureTestingModule({
      imports: [App],
    }).compileComponents();
  });

  it('should create the app', () => {
    const fixture = TestBed.createComponent(App);
    const app = fixture.componentInstance;
    expect(app).toBeTruthy();
  });

  it('should render title', async () => {
    // JSDOM has no layout; give sections positions below the viewport top.
    const geometry = vi.spyOn(Element.prototype, 'getBoundingClientRect').mockReturnValue({ top: 200 } as DOMRect);
    const fixture = TestBed.createComponent(App);
    await fixture.whenStable();
    const compiled = fixture.nativeElement as HTMLElement;
    expect(compiled.querySelector('h1')?.textContent).toContain('Francisco Jos\u00e9');
    geometry.mockRestore();
  });
});
